function normalizeName(text) {
  return String(text ?? '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

const teachers = db.prepare("SELECT id, full_name FROM users WHERE role = 'teacher'").all();
function teacherId(label) {
  const first = normalizeName(TEACHER_LABELS[label] ?? label);
  const found = teachers.find((row) => {
    const name = normalizeName(row.full_name);
    return name === first || name.startsWith(`${first} `);
  });
  return found ? found.id : null;
}

